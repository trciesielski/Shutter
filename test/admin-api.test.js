async function upload(kind,name,bytes,type,extra={}){
 const start=await call('POST','uploads',{kind,name,size:bytes.length,type,...extra});
 if(start.status!==201)return start;
 const parts=[];
 for(let n=1;n<=start.body.parts;n++){
  const r=await call('PUT',`uploads/${start.body.session}/parts/${n}`,undefined,{raw:bytes.slice((n-1)*PART_SIZE,n*PART_SIZE)});
  if(r.status!==200)return r;
  parts.push(r.body);
 }
 return call('POST',`uploads/${start.body.session}/complete`,{parts});
}
